def normalize_text(text):

    text = text.lower().strip()

    replacements = {

        "ي": "ی",
        "ى": "ی",
        "ك": "ک",
        "ۀ": "ه",
        "ة": "ه",

        "\u200c": " ",
        "‌": " "
    }

    for old, new in replacements.items():

        text = text.replace(
            old,
            new
        )

    text = re.sub(
        r"\s+",
        " ",
        text
    )

    return text


def contains_any(text, words):

    return any(
        word in text
        for word in words
    )


